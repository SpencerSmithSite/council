#!/usr/bin/env python3
"""Generate the theme catalogue for both apps from shared/themes.json.

shared/themes.json is the single source of truth for the named themes: their
ids, labels, order, and the identifying colours of each light and dark
variant. This writes the same data out twice:

  lib/src/theme/themes.g.dart
      `kNamedThemes`, as a `part of 'themes.dart'` so it can call the private
      `_palette` derivation there. The public API of themes.dart is unchanged.

  apple/CouncilCore/Sources/CouncilCore/Themes/ThemeCatalogue.g.swift
      `ThemeCatalogue.named`, the same themes as Swift values, fed to the
      Swift port of the derivation.

The derived colours (container tints, the lifted separator and secondary
label) are not generated: each app computes them, and both are held to
shared/golden/themes/derived.json.

Usage:
  python3 tools/generate_themes.py           # rewrite both files
  python3 tools/generate_themes.py --check   # exit 1 if either is stale

Standard library only, so CI can run it before installing any toolchain.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared" / "themes.json"
DART_OUT = ROOT / "lib" / "src" / "theme" / "themes.g.dart"
SWIFT_OUT = (
    ROOT / "apple" / "CouncilCore" / "Sources" / "CouncilCore" / "Themes"
    / "ThemeCatalogue.g.swift"
)

# The order fields are written in, which is also the order `_palette` and
# `ThemeVariant` take them. `error` is optional; the derivation supplies a
# default red per brightness when it is absent.
REQUIRED = ["bg", "surface", "surface2", "text", "subtext", "separator",
            "accent", "onAccent"]
OPTIONAL = ["error"]
FIELDS = REQUIRED + OPTIONAL

# "default" is the platform look, resolved specially by both apps.
RESERVED_IDS = {"default"}

HEADER = ("Generated by tools/generate_themes.py — edit shared/themes.json, "
          "not this file.")
HEADER2 = ("CI fails when this is stale: "
           "python3 tools/generate_themes.py --check")

_ID = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
_COLOUR = re.compile(r"^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")


class CatalogueError(Exception):
    pass


def argb(colour: str, where: str) -> int:
    """`#RRGGBB` (opaque) or `#AARRGGBB` to a 32-bit ARGB integer."""
    if not isinstance(colour, str) or not _COLOUR.match(colour):
        raise CatalogueError(f"{where}: {colour!r} is not #RRGGBB or #AARRGGBB")
    digits = colour[1:]
    if len(digits) == 6:
        digits = "FF" + digits
    return int(digits, 16)


def load(path: Path = SOURCE) -> list[dict]:
    """Read and validate the catalogue. Returns the themes, colours as ints."""
    doc = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict) or not isinstance(doc.get("themes"), list):
        raise CatalogueError(f"{path}: expected an object with a 'themes' list")
    unknown_top = set(doc) - {"comment", "themes"}
    if unknown_top:
        raise CatalogueError(f"{path}: unknown top-level keys {sorted(unknown_top)}")

    themes, seen = [], set()
    for i, raw in enumerate(doc["themes"]):
        where = f"themes[{i}]"
        if not isinstance(raw, dict):
            raise CatalogueError(f"{where}: expected an object")
        unknown = set(raw) - {"id", "label", "note", "light", "dark"}
        if unknown:
            raise CatalogueError(f"{where}: unknown keys {sorted(unknown)}")
        tid = raw.get("id")
        if not isinstance(tid, str) or not _ID.match(tid):
            raise CatalogueError(f"{where}: id {tid!r} must be lowercase-kebab")
        where = f"theme {tid!r}"
        if tid in RESERVED_IDS:
            raise CatalogueError(f"{where}: id is reserved for the platform look")
        if tid in seen:
            raise CatalogueError(f"{where}: duplicate id")
        seen.add(tid)
        label = raw.get("label")
        if not isinstance(label, str) or not label.strip():
            raise CatalogueError(f"{where}: needs a label")
        note = raw.get("note", "")
        if not isinstance(note, str):
            raise CatalogueError(f"{where}: note must be a string")

        theme = {"id": tid, "label": label, "note": note.strip()}
        for variant in ("light", "dark"):
            v = raw.get(variant)
            if not isinstance(v, dict):
                raise CatalogueError(f"{where}: missing {variant} variant")
            missing = [k for k in REQUIRED if k not in v]
            if missing:
                raise CatalogueError(f"{where}.{variant}: missing {missing}")
            extra = sorted(set(v) - set(FIELDS))
            if extra:
                raise CatalogueError(f"{where}.{variant}: unknown fields {extra}")
            theme[variant] = {
                k: argb(v[k], f"{where}.{variant}.{k}") for k in FIELDS if k in v
            }
        themes.append(theme)
    if not themes:
        raise CatalogueError(f"{path}: no themes")
    return themes


# --- Dart -------------------------------------------------------------------

def _dart_string(s: str) -> str:
    escaped = (s.replace("\\", "\\\\").replace("'", "\\'")
               .replace("$", "\\$").replace("\n", "\\n"))
    return f"'{escaped}'"


def _comment(text: str, indent: str, width: int = 80) -> list[str]:
    if not text:
        return []
    prefix = f"{indent}// "
    return textwrap.wrap(text, width=width, initial_indent=prefix,
                         subsequent_indent=prefix, break_long_words=False,
                         break_on_hyphens=False)


def render_dart(themes: list[dict]) -> str:
    out = [
        f"// {HEADER}",
        f"// {HEADER2}",
        "",
        "part of 'themes.dart';",
        "",
        "/// The full theme catalogue, in the order the user gave. \"Default\" is "
        "prepended",
        "/// by the picker; everything below is a fixed community palette.",
        "final List<NamedTheme> kNamedThemes = [",
    ]
    for i, t in enumerate(themes):
        if i:
            out.append("")
        out += _comment(t["note"], "  ")
        out += [
            "  NamedTheme(",
            f"    id: {_dart_string(t['id'])},",
            f"    label: {_dart_string(t['label'])},",
        ]
        for variant in ("light", "dark"):
            out += [
                f"    {variant}: _palette(",
                f"      brightness: Brightness.{variant},",
            ]
            for k, value in t[variant].items():
                out.append(f"      {k}: const Color(0x{value:08X}),")
            out.append("    ),")
        out.append("  ),")
    out.append("];")
    return "\n".join(out) + "\n"


# --- Swift ------------------------------------------------------------------

def _swift_string(s: str) -> str:
    escaped = (s.replace("\\", "\\\\").replace('"', '\\"')
               .replace("\n", "\\n"))
    return f'"{escaped}"'


def render_swift(themes: list[dict]) -> str:
    out = [
        f"// {HEADER}",
        f"// {HEADER2}",
        "",
        "extension ThemeCatalogue {",
        "    /// The named themes, in picker order. \"Default\" is not among them: "
        "it follows",
        "    /// the platform's own colours (see `ThemeCatalogue.defaultThemeID`).",
        "    public static let named: [ThemeCore] = [",
    ]
    for i, t in enumerate(themes):
        if i:
            out.append("")
        out += _comment(t["note"], "        ", width=100)
        out += [
            "        ThemeCore(",
            f"            id: {_swift_string(t['id'])},",
            f"            label: {_swift_string(t['label'])},",
        ]
        for variant in ("light", "dark"):
            out.append(f"            {variant}: ThemeVariant(")
            items = list(t[variant].items())
            for j, (k, value) in enumerate(items):
                comma = "," if j < len(items) - 1 else ""
                out.append(f"                {k}: RGBA(argb: 0x{value:08X}){comma}")
            out.append("            )" + ("," if variant == "light" else ""))
        out.append("        )" + ("," if i < len(themes) - 1 else ""))
    out += ["    ]", "}"]
    return "\n".join(out) + "\n"


# --- Driver -----------------------------------------------------------------

def outputs(themes: list[dict]) -> dict[Path, str]:
    return {DART_OUT: render_dart(themes), SWIFT_OUT: render_swift(themes)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if a generated file is stale")
    args = parser.parse_args(argv)

    try:
        themes = load()
    except (CatalogueError, json.JSONDecodeError) as e:
        print(f"generate_themes: {e}", file=sys.stderr)
        return 2

    stale = []
    for path, text in outputs(themes).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        rel = path.relative_to(ROOT)
        if args.check:
            stale.append(rel)
            diff = difflib.unified_diff(
                (current or "").splitlines(keepends=True),
                text.splitlines(keepends=True),
                fromfile=f"{rel} (committed)", tofile=f"{rel} (from themes.json)",
                n=1)
            sys.stderr.writelines(list(diff)[:40])
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")

    if stale:
        print("generate_themes: stale, run python3 tools/generate_themes.py: "
              + ", ".join(str(p) for p in stale), file=sys.stderr)
        return 1
    if args.check:
        print(f"generate_themes: {len(themes)} themes, generated files current")
    return 0


if __name__ == "__main__":
    sys.exit(main())

import 'dart:convert';
import 'dart:io';

import 'package:council/src/reader/passage_segments.dart';
import 'package:flutter_test/flutter_test.dart';

/// What the reader's segmenter makes of every passage in
/// `shared/golden/segments/segments.json`.
///
/// Highlights and notes are stored against the content unit as character
/// offsets (`PassageSegment.start`/`end`, Dart `String` indices: UTF-16 code
/// units). The native Apple app installs over this one and reads the same user
/// database, so its port of `passage_segments.dart`
/// (`apple/CouncilCore/Sources/CouncilCore/Reading/PassageSegments.swift`) has
/// to cut every passage at exactly the same offsets. It checks itself against
/// this same file in `SegmentsGoldenTests`.
///
/// The fixture carries its inputs, so neither side needs the corpus. The
/// inputs are chosen by `tools/build_segment_goldens.py`; everything else in
/// the file is written by this test from the Dart code. After an intended
/// change to the segmenter, regenerate the outputs with
///
///     flutter test test/segments_golden_test.dart --dart-define=UPDATE_GOLDENS=true
///
/// See `shared/golden/segments/README.md` for the format.
void main() {
  const update = bool.fromEnvironment('UPDATE_GOLDENS');
  const path = 'shared/golden/segments/segments.json';

  final golden =
      jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;
  final cases = (golden['cases'] as List).cast<Map<String, dynamic>>();

  if (update) {
    test('rewrite $path', () {
      final fixture = <String, Object?>{
        'comment': 'Generated by test/segments_golden_test.dart '
            '(--dart-define=UPDATE_GOLDENS=true) from the inputs chosen by '
            'tools/build_segment_goldens.py. What '
            'lib/src/reader/passage_segments.dart makes of each passage. '
            'Checked by the Flutter test and by apple/CouncilCore '
            'SegmentsGoldenTests. See README.md beside this file.',
        'cases': [for (final c in cases) _record(c)],
      };
      File(path).writeAsStringSync('${_Json.encode(fixture)}\n');
    });
    return;
  }

  test('case ids are unique and every case has its outputs', () {
    final ids = cases.map((c) => c['id']).toList();
    expect(ids.toSet(), hasLength(ids.length));
    for (final c in cases) {
      expect(c.containsKey('segments'), isTrue,
          reason: '${c['id']} has no outputs; regenerate with '
              '--dart-define=UPDATE_GOLDENS=true');
    }
  });

  group('segments golden', () {
    for (final recorded in cases) {
      final id = recorded['id'] as String;
      test(id, () {
        final actual = _record(recorded);
        for (final field in ['kind', 'nouns']) {
          expect(actual[field], recorded[field], reason: '$id: $field');
        }
        final segments = actual['segments'] as List;
        final expected = recorded['segments'] as List;
        for (var i = 0; i < segments.length && i < expected.length; i++) {
          expect(segments[i], expected[i], reason: '$id: segment $i');
        }
        expect(segments.length, expected.length, reason: '$id: segment count');
        final selections = actual['selections'] as List;
        final expectedSelections = recorded['selections'] as List;
        expect(selections.length, expectedSelections.length,
            reason: '$id: selection count');
        for (var i = 0; i < selections.length; i++) {
          expect(selections[i], expectedSelections[i],
              reason: '$id: selection $i');
        }
      });
    }
  });

  // Properties of the Dart code rather than of the fixture: if one of these
  // fails, the segmenter is producing offsets a highlight can't be stored
  // against, and regenerating the fixture would only record the damage.
  group('segment invariants', () {
    for (final c in cases) {
      test(c['id'] as String, () {
        final content = c['content'] as String;
        final passage = segmentPassage(content);
        var previousEnd = 0;
        for (final s in passage.segments) {
          final where = '${c['id']} segment ${s.index}';
          expect(s.start, greaterThanOrEqualTo(previousEnd), reason: where);
          expect(s.end, greaterThan(s.start), reason: where);
          expect(s.end, lessThanOrEqualTo(content.length), reason: where);
          expect(s.text, isNotEmpty, reason: where);
          expect(s.text, s.text.trim(), reason: where);
          final span = content.substring(s.start, s.end);
          if (passage.kind == SegmentKind.verse) {
            // The span includes the number; the text is what follows it.
            expect(span.endsWith(s.text), isTrue, reason: where);
          } else {
            expect(span, s.text, reason: where);
          }
          previousEnd = s.end;
        }
      });
    }
  });
}

/// A case's inputs followed by the outputs the Dart code produces for them.
Map<String, Object?> _record(Map<String, dynamic> input) {
  final content = input['content'] as String;
  final unitTitle = input['unitTitle'] as String?;
  final extra = (input['extraSelections'] as List? ?? const [])
      .map((s) => (s as List).cast<int>())
      .toList();

  final passage = segmentPassage(content);
  final segments = passage.segments;

  return {
    'id': input['id'],
    'why': input['why'],
    'unitTitle': unitTitle,
    'content': content,
    if (input.containsKey('extraSelections')) 'extraSelections': extra,
    'kind': passage.kind.name,
    'nouns': [passage.noun(0), passage.noun(1), passage.noun(2)],
    'segments': [
      for (final s in segments) [s.index, s.start, s.end, s.text, s.number],
    ],
    'selections': [
      for (final selected in _selections(segments.length, extra, input['id']))
        {
          'selected': selected,
          'reference':
              referenceFor(unitTitle, [for (final i in selected) segments[i]]),
          'quote': quoteFor(passage, selected),
        },
    ],
  };
}

/// The selections recorded for a passage of [count] segments: a standard set
/// covering single segments, adjacent pairs (cited "4, 5"), runs ("4–6"), gaps
/// (an ellipsis in the quote), unsorted and repeated indices, then any extra
/// selections the case asks for.
List<List<int>> _selections(int count, List<List<int>> extra, Object? id) {
  final last = count - 1;
  final standard = <List<int>>[
    [],
    [0],
    [last],
    [0, 1],
    [1, 0],
    [0, 1, 2],
    [0, 2],
    [0, 2, 3, 5],
    [last - 1, last],
    [1, 1],
    [0, last],
    [for (var i = 0; i < (count <= 20 ? count : 10); i++) i],
  ];
  final seen = <String>{};
  final out = <List<int>>[];
  for (final s in standard) {
    if (s.any((i) => i < 0 || i >= count)) continue;
    if (seen.add(s.join(','))) out.add(s);
  }
  for (final s in extra) {
    if (s.any((i) => i < 0 || i >= count)) {
      throw StateError('$id: extra selection $s is out of range ($count)');
    }
    if (seen.add(s.join(','))) out.add(s);
  }
  return out;
}

/// JSON with one segment or index list per line, and invisible characters
/// escaped so the fixture can be read and diffed: the content strings are full
/// of no-break spaces, byte-order marks and line separators that are the
/// point of the case and would otherwise be indistinguishable from spaces or
/// missing altogether in an editor.
abstract final class _Json {
  static String encode(Object? value, [String indent = '']) {
    if (value is Map) {
      if (value.isEmpty) return '{}';
      final inner = '$indent  ';
      final entries = value.entries
          .map((e) => '$inner${_string(e.key as String)}: '
              '${encode(e.value, inner)}')
          .join(',\n');
      return '{\n$entries\n$indent}';
    }
    if (value is List) {
      if (value.every((v) => v == null || v is num || v is String)) {
        return '[${value.map((v) => encode(v, indent)).join(', ')}]';
      }
      final inner = '$indent  ';
      return '[\n${value.map((v) => '$inner${encode(v, inner)}').join(',\n')}'
          '\n$indent]';
    }
    if (value is String) return _string(value);
    return jsonEncode(value);
  }

  static String _string(String s) {
    final out = StringBuffer('"');
    for (final unit in s.codeUnits) {
      switch (unit) {
        case 0x22:
          out.write(r'\"');
        case 0x5C:
          out.write(r'\\');
        case 0x0A:
          out.write(r'\n');
        case 0x0D:
          out.write(r'\r');
        case 0x09:
          out.write(r'\t');
        default:
          if (_invisible(unit)) {
            out.write('\\u${unit.toRadixString(16).padLeft(4, '0')}');
          } else {
            out.writeCharCode(unit);
          }
      }
    }
    out.write('"');
    return out.toString();
  }

  static bool _invisible(int unit) =>
      unit < 0x20 ||
      (unit >= 0x7F && unit <= 0xA0) ||
      unit == 0xAD ||
      unit == 0x1680 ||
      (unit >= 0x2000 && unit <= 0x200F) ||
      (unit >= 0x2028 && unit <= 0x202F) ||
      (unit >= 0x205F && unit <= 0x206F) ||
      unit == 0x3000 ||
      unit == 0xFEFF;
}

import 'dart:convert';
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';

import 'package:council/src/theme/palette.dart';
import 'package:council/src/theme/themes.dart';

/// Every colour the palette derivation produces, for every theme in both
/// brightnesses, against `shared/golden/themes/derived.json`.
///
/// A theme is defined by nine identifying colours (`shared/themes.json`); the
/// rest — the container tints, the lifted separator and secondary label — are
/// computed by `_palette` in `themes.dart` through `containerPair`,
/// `legibleSeparator` and `legibleSecondaryLabel`. The native Apple app ports
/// that derivation to Swift (`apple/CouncilCore/Sources/CouncilCore/Themes/`)
/// and checks itself against this same file, so a change to the arithmetic on
/// either side shows up as a diff here rather than as two apps quietly
/// disagreeing about what Gruvbox looks like.
///
/// The Apple platform palette is recorded too: the native app's "Default"
/// theme uses SwiftUI's own semantic colours for everything that has one, and
/// takes only the derived container tints from the ported `applePalette`.
///
/// Regenerate after an intended change with
///
///     flutter test test/theme_golden_test.dart --dart-define=UPDATE_GOLDENS=true
///
/// Colours are `#AARRGGBB`, rounded to 8 bits per channel exactly as
/// `Color.toARGB32` rounds them.
void main() {
  const update = bool.fromEnvironment('UPDATE_GOLDENS');
  const path = 'shared/golden/themes/derived.json';

  final derived = <String, dynamic>{
    'comment': 'Generated by test/theme_golden_test.dart '
        '(--dart-define=UPDATE_GOLDENS=true). Every colour role the palette '
        'derivation sets, per theme and brightness, as #AARRGGBB. Checked by '
        'the Flutter test and by apple/CouncilCore ThemeGoldenTests.',
    'themes': [
      for (final t in kNamedThemes)
        {
          'id': t.id,
          'light': _roles(t.light),
          'dark': _roles(t.dark),
        },
    ],
    'platform': {
      'apple': {
        'light': _roles(applePalette(Brightness.light)),
        'dark': _roles(applePalette(Brightness.dark)),
      },
    },
  };

  if (update) {
    test('rewrite $path', () {
      final file = File(path);
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(
          '${const JsonEncoder.withIndent('  ').convert(derived)}\n');
    });
    return;
  }

  final golden =
      jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;
  final goldenThemes = (golden['themes'] as List).cast<Map<String, dynamic>>();

  test('the golden lists the catalogue, in order', () {
    expect(goldenThemes.map((t) => t['id']).toList(),
        kNamedThemes.map((t) => t.id).toList(),
        reason: 'the catalogue changed; regenerate with '
            '--dart-define=UPDATE_GOLDENS=true');
  });

  group('derived palette', () {
    for (final t in derived['themes'] as List) {
      final id = t['id'] as String;
      final expected = goldenThemes.firstWhere((g) => g['id'] == id,
          orElse: () => const {});
      for (final variant in const ['light', 'dark']) {
        test('$id ($variant)', () {
          expect(t[variant], expected[variant]);
        });
      }
    }
  });

  group('Apple platform palette', () {
    final apple = (golden['platform'] as Map)['apple'] as Map;
    final ours = (derived['platform'] as Map)['apple'] as Map;
    for (final variant in const ['light', 'dark']) {
      test(variant, () => expect(ours[variant], apple[variant]));
    }
  });
}

String _hex(Color c) =>
    '#${c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()}';

/// Every [ColorScheme] role `_palette` and `applePalette` set, then the three
/// [AppPalette] extras. Order is the file's order, kept stable for diffs.
Map<String, String> _roles(AppPalette p) {
  final s = p.scheme;
  return {
    'primary': _hex(s.primary),
    'onPrimary': _hex(s.onPrimary),
    'secondary': _hex(s.secondary),
    'onSecondary': _hex(s.onSecondary),
    'error': _hex(s.error),
    'onError': _hex(s.onError),
    'primaryContainer': _hex(s.primaryContainer),
    'onPrimaryContainer': _hex(s.onPrimaryContainer),
    'secondaryContainer': _hex(s.secondaryContainer),
    'onSecondaryContainer': _hex(s.onSecondaryContainer),
    'errorContainer': _hex(s.errorContainer),
    'onErrorContainer': _hex(s.onErrorContainer),
    'surface': _hex(s.surface),
    'onSurface': _hex(s.onSurface),
    'onSurfaceVariant': _hex(s.onSurfaceVariant),
    'surfaceContainerLowest': _hex(s.surfaceContainerLowest),
    'surfaceContainerLow': _hex(s.surfaceContainerLow),
    'surfaceContainer': _hex(s.surfaceContainer),
    'surfaceContainerHigh': _hex(s.surfaceContainerHigh),
    'surfaceContainerHighest': _hex(s.surfaceContainerHighest),
    'outline': _hex(s.outline),
    'outlineVariant': _hex(s.outlineVariant),
    'groupedBackground': _hex(p.groupedBackground),
    'separator': _hex(p.separator),
    'secondaryLabel': _hex(p.secondaryLabel),
  };
}

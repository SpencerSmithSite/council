/// Prose of exactly [length] UTF-16 code units, varied enough that a cut in
/// the wrong place shows.
String _prose(int length, {int seed = 0}) {
  const words = [
    'In', 'the', 'beginning', 'was', 'the', 'Word,', 'and', 'the', 'Word',
    'was', 'with', 'God,', 'and', 'the', 'Word', 'was', 'God.', 'The', 'same',
    'was', 'in', 'the', 'beginning', 'with', 'God.', 'All', 'things', 'were',
    'made', 'by', 'him;', 'and', 'without', 'him', 'was', 'not', 'any',
    'thing', 'made', 'that', 'was', 'made.',
  ];
  final out = StringBuffer();
  var i = seed;
  while (out.length < length) {
    if (out.isNotEmpty) out.write(' ');
    out.write(words[i % words.length]);
    i++;
  }
  return out.toString().substring(0, length);
}


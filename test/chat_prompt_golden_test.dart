/// A case's inputs followed by what ChatPrompt builds from them.
Map<String, Object?> _record(_Case c) {
  final built = ChatPrompt.build(
    question: c.question,
    retrieved: c.retrieved,
    pinned: c.pinned,
    contextBudgetChars: c.budget,
  )!;
  final passageCount = c.retrieved.length + (c.pinned == null ? 0 : 1);
  final citations = [for (final citation in built.citations) citation.toJson()];
  return {
    'id': c.id,
    'why': c.why,
    'question': c.question,
    'contextBudgetChars': c.budget,
    'pinned': c.pinned == null
        ? null
        : {
            'contentUnitId': c.pinned!.contentUnitId,
            'quote': c.pinned!.quote,
            'reference': c.pinned!.reference,
            'sourceTitle': c.pinned!.sourceTitle,
          },
    'retrieved': c.retrieved,
    'perPassage': ChatPrompt.perPassageBudget(c.budget, passageCount),
    'prompt': _wire(built.prompt),
    'citations': citations,
    'citationsJson': jsonEncode(citations),
    'traceable': [for (final citation in built.citations) citation.isTraceable],
  };
}

/// [s] as a backend receives it: UTF-8, in which a lone surrogate (half of a
/// character cut by the budget) becomes U+FFFD.
String _wire(String s) => utf8.decode(utf8.encode(s));

/// JSON with invisible characters escaped, so the fixture can be read and
/// diffed: the cases are full of no-break spaces, byte-order marks and
/// combining marks that are the point of the case and would otherwise be
/// indistinguishable from spaces, or missing altogether, in an editor.
/// U+FFFD is escaped too, so a cut surrogate pair is visible.
abstract final class _Json {
  static String encode(Object? value, [String indent = '']) {
    if (value is Map) {
      if (value.isEmpty) return '{}';
      final inner = '$indent  ';
      final entries = value.entries
          .map((e) => '$inner${_string(e.key as String)}: '
              '${encode(e.value, inner)}')
          .join(',\n');
      return '{\n$entries\n$indent}';
    }
    if (value is List) {
      if (value.isEmpty) return '[]';
      if (value.every((v) => v == null || v is num || v is bool)) {
        return '[${value.map((v) => encode(v, indent)).join(', ')}]';
      }
      final inner = '$indent  ';
      return '[\n${value.map((v) => '$inner${encode(v, inner)}').join(',\n')}'
          '\n$indent]';
    }
    if (value is String) return _string(value);
    return jsonEncode(value);
  }

  static String _string(String s) {
    final out = StringBuffer('"');
    for (final unit in s.codeUnits) {
      switch (unit) {
        case 0x22:
          out.write(r'\"');
        case 0x5C:
          out.write(r'\\');
        case 0x0A:
          out.write(r'\n');
        case 0x0D:
          out.write(r'\r');
        case 0x09:
          out.write(r'\t');
        default:
          if (_invisible(unit)) {
            out.write('\\u${unit.toRadixString(16).padLeft(4, '0')}');
          } else {
            out.writeCharCode(unit);
          }
      }
    }
    out.write('"');
    return out.toString();
  }

  static bool _invisible(int unit) =>
      unit < 0x20 ||
      (unit >= 0x7F && unit <= 0xA0) ||
      unit == 0xAD ||
      (unit >= 0x0300 && unit <= 0x036F) ||
      unit == 0x1680 ||
      (unit >= 0x2000 && unit <= 0x200F) ||
      (unit >= 0x2028 && unit <= 0x202F) ||
      (unit >= 0x205F && unit <= 0x206F) ||
      unit == 0x3000 ||
      unit == 0xFEFF ||
      unit == 0xFFFD;
}

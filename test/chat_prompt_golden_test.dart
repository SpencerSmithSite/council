/// What the chat screen sends a backend, for every case in
/// `shared/golden/prompts/prompts.json`.
///
/// The native Apple app builds the same prompt in Swift
/// (`apple/CouncilCore/Sources/CouncilCore/Inference/ChatPrompt.swift`) and
/// checks itself against this file in `ChatPromptGoldenTests`. The two have to
/// agree character for character: the per-passage budget, where a long passage
/// is cut (in UTF-16 code units, then right-trimmed with Dart's whitespace
/// set), the anchor sentence for a pinned passage, and the citation JSON that
/// both apps store in `conversation_messages.citations`.
///
/// The cases are defined below, inputs and all; the fixture is written from
/// them. After an intended change to the prompt, or to the cases, regenerate
/// it with
///
///     flutter test test/chat_prompt_golden_test.dart --dart-define=UPDATE_GOLDENS=true
///
/// See `shared/golden/prompts/README.md` for the format.
void main() {
  const update = bool.fromEnvironment('UPDATE_GOLDENS');
  const path = 'shared/golden/prompts/prompts.json';

  final fixture = <String, Object?>{
    'comment': 'Generated by test/chat_prompt_golden_test.dart '
        '(--dart-define=UPDATE_GOLDENS=true) from the cases defined there. '
        'What lib/src/services/inference/chat_prompt.dart builds for each '
        'question. Checked by the Flutter test and by apple/CouncilCore '
        'ChatPromptGoldenTests. See README.md beside this file.',
    'system': ChatPrompt.systemPrompt,
    'cases': [for (final c in _cases()) _record(c)],
  };
  final encoded = '${_Json.encode(fixture)}\n';

  if (update) {
    test('rewrite $path', () {
      Directory('shared/golden/prompts').createSync(recursive: true);
      File(path).writeAsStringSync(encoded);
    });
    return;
  }

  final file = File(path);
  final recorded = file.existsSync()
      ? jsonDecode(file.readAsStringSync()) as Map<String, dynamic>
      : const <String, dynamic>{};
  final recordedCases = {
    for (final c in (recorded['cases'] as List? ?? const []))
      (c as Map<String, dynamic>)['id']: c,
  };

  test('the system prompt', () {
    expect(recorded['system'], ChatPrompt.systemPrompt);
  });

  group('prompts golden', () {
    for (final built in fixture['cases'] as List) {
      final actual = built as Map<String, Object?>;
      final id = actual['id'] as String;
      test(id, () {
        final expected = recordedCases[id];
        expect(expected, isNotNull,
            reason: '$id is not in $path; regenerate with '
                '--dart-define=UPDATE_GOLDENS=true');
        // Round-tripped through JSON so both sides are compared in the form
        // the file holds them.
        final actualJson =
            jsonDecode(_Json.encode(actual)) as Map<String, dynamic>;
        for (final field in actualJson.keys) {
          expect(actualJson[field], expected![field], reason: '$id: $field');
        }
      });
    }
  });

  test('the file is exactly what the cases produce', () {
    // Catches what the per-case checks can't: a case removed from the code
    // but left in the file, or a change in formatting.
    expect(file.readAsStringSync(), encoded,
        reason: 'regenerate with --dart-define=UPDATE_GOLDENS=true');
  });

  test('every case id is unique', () {
    final ids = _cases().map((c) => c.id).toList();
    expect(ids.toSet(), hasLength(ids.length));
  });
}


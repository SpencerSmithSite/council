import 'dart:convert';
import 'dart:io';

import 'package:council/src/services/updates/app_version.dart';
import 'package:council/src/services/updates/release_manifest.dart';
import 'package:flutter_test/flutter_test.dart';

/// What the update check makes of the inputs in
/// `shared/golden/updates/updates.json`: version strings, version orderings,
/// download file names and whole manifests.
///
/// The native Apple app ports `app_version.dart` and `release_manifest.dart`
/// to `apple/CouncilCore/Sources/CouncilCore/Updates/` and checks itself
/// against this same file in `UpdatesGoldenTests`. Both apps read the one
/// `updates.json` on the site, so they must agree on which entries it offers,
/// and the parsing leans on Dart behaviour that is easy to get subtly wrong in
/// another language: `int.tryParse` accepting `0x` and surrounding
/// whitespace, `is int` rejecting `7.0`, and `as String?` throwing (failing
/// the whole manifest, not just the entry) on a value of the wrong type.
///
/// The inputs are written by hand in the fixture; everything else is written
/// by this test from the Dart code. After changing the inputs or the Dart,
/// regenerate with
///
///     flutter test test/updates_golden_test.dart --dart-define=UPDATE_GOLDENS=true
///
/// See `shared/golden/updates/README.md`.
void main() {
  const update = bool.fromEnvironment('UPDATE_GOLDENS');
  const path = 'shared/golden/updates/updates.json';

  final golden =
      jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;
  final versions = (golden['versions'] as List).cast<Map<String, dynamic>>();
  final comparisons = (golden['comparisons'] as List).cast<Map<String, dynamic>>();
  final fileNames = (golden['fileNames'] as List).cast<Map<String, dynamic>>();
  final manifests = (golden['manifests'] as List).cast<Map<String, dynamic>>();

  if (update) {
    test('rewrite $path', () {
      final fixture = <String, Object?>{
        'comment': 'Inputs written by hand; outputs generated by '
            'test/updates_golden_test.dart (--dart-define=UPDATE_GOLDENS=true) '
            'from lib/src/services/updates/. Checked by the Flutter test and '
            'by apple/CouncilCore UpdatesGoldenTests. See README.md beside '
            'this file.',
        'versions': [for (final v in versions) _version(v)],
        'comparisons': [for (final c in comparisons) _comparison(c)],
        'fileNames': [for (final f in fileNames) _fileName(f)],
        'manifests': [for (final m in manifests) _manifest(m)],
      };
      File(path).writeAsStringSync(
          '${const JsonEncoder.withIndent(' ').convert(fixture)}\n');
    });
    return;
  }

  group('updates golden', () {
    for (final v in versions) {
      test('version ${jsonEncode(v['raw'])} build ${v['build']}', () {
        expect(_version(v), v);
      });
    }
    for (final c in comparisons) {
      test('compare ${c['a']} with ${c['b']}', () {
        expect(_comparison(c), c);
      });
    }
    for (final f in fileNames) {
      test('file name of ${f['url']}', () {
        expect(_fileName(f), f);
      });
    }
    for (final m in manifests) {
      test('manifest: ${m['id']}', () {
        expect(_manifest(m), m);
      });
    }
  });
}

Map<String, Object?> _versionJson(AppVersion v) => {
      'parts': v.parts,
      'build': v.build,
      'name': v.name,
      'string': v.toString(),
    };

Map<String, Object?> _version(Map<String, dynamic> input) {
  final raw = input['raw'] as String?;
  final build = input['build'] as int?;
  final parsed = AppVersion.tryParse(raw, build: build);
  return {
    'raw': raw,
    if (input.containsKey('build')) 'build': build,
    'result': parsed == null ? null : _versionJson(parsed),
  };
}

Map<String, Object?> _comparison(Map<String, dynamic> input) {
  final a = AppVersion.tryParse(input['a'] as String)!;
  final b = AppVersion.tryParse(input['b'] as String)!;
  return {
    'a': input['a'],
    'b': input['b'],
    'order': a.compareTo(b).sign,
    'equal': a == b,
    'sameHash': a.hashCode == b.hashCode,
  };
}

Map<String, Object?> _fileName(Map<String, dynamic> input) {
  final url = input['url'] as String;
  final release = PlatformRelease(
    platform: 'macos',
    delivery: ReleaseDelivery.download,
    url: Uri.parse(url),
    version: const AppVersion([2026, 8, 2], build: 7),
  );
  return {'url': url, 'fileName': release.fileName};
}

/// `UpdateService.fetchManifest`'s view of a body: `null` for anything that
/// is not a JSON object or that `fromJson` throws on (whatever it throws), so
/// the Swift side only has to agree that it fails.
Map<String, Object?> _manifest(Map<String, dynamic> input) {
  final body = input['json'] as String;
  Object? result;
  final decoded = jsonDecode(body);
  if (decoded is Map<String, dynamic>) {
    try {
      final m = ReleaseManifest.fromJson(decoded);
      final ids = m.platforms.keys.toList()..sort();
      result = {
        'version': _versionJson(m.version),
        'notes': m.notes,
        'page': m.page?.toString(),
        'platforms': {
          for (final id in ids) id: _release(m.platforms[id]!),
        },
      };
    } catch (_) {
      result = null;
    }
  }
  return {'id': input['id'], 'json': body, 'result': result};
}

Map<String, Object?> _release(PlatformRelease r) => {
      'platform': r.platform,
      'delivery': r.delivery.name,
      'url': r.url.toString(),
      'version': _versionJson(r.version),
      'bytes': r.bytes,
      'sha256': r.sha256,
      'megabytes': r.megabytes,
      'fileName': r.fileName,
    };
